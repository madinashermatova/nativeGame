export let map = [];
export let ROWS = 0;
export let COLS = 0;

export function loadLevel(levelIndex) {
  if (levelIndex >= levels.length) {
    gameState.state = 'won';
    return;
  }
  gameState.currentLevel = levelIndex;
  gameState.foundry = levelIndex === 2 ? createFoundry() : null;
  gameState.toxic = levelIndex === 3 ? createToxic() : null;

  const layout = levels[levelIndex];
  ROWS = layout.length;
  COLS = layout[0].length;
  map = Array.from({ length: ROWS }, () => Array(COLS).fill('.'));
  gameState.coins = [];
  gameState.enemies = [];
  gameState.hazards = [];
  gameState.saws = [];
  gameState.jumpPads = [];
  gameState.crumbles = [];
  gameState.bloodParticles = [];
  gameState.elements = [];
  gameState.lasers = [];
  gameState.checkpoints = [];
  gameState.checkpoint = 0;
  gameState.levelTick = 0;

  for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
      const char = layout[y][x];

      if (char === '#') {
        map[y][x] = '#';
      }
      else if (char === 'L') {
        gameState.lasers.push({x: x * T, y: 13 * T - 64, w: 32, h: 64, phase: x * 7});
      }
      else if (char === 'K') {
        gameState.checkpoints.push({x: x * T, y: y * T, active: false});
      }
      else if (char === 'F' || char === 'U') {
        gameState.elements.push({type: char === 'F' ? 'fire' : 'water',
          x: x * T, y: y * T, w: T, h: T, tx: x, ty: y,
          phase: Math.floor(x / 8) * 17});
      }
      else if (char === 'B') {
        map[y][x] = 'B';
        gameState.crumbles.push({
          x: x * T,
          y: y * T,
          w: T,
          h: T,
          tx: x,
          ty: y,
          timer: 0,
          collapsed: false,
          respawnTimer: 0
        });
      }
      else if (char === 'J') {
        gameState.jumpPads.push({
          x: x * T + 2,
          y: y * T + 8,
          w: T - 4,
          h: 8,
          tx: x,
          ty: y,
          anim: 0
        });
      }
      else if (char === 'C') {
        gameState.coins.push({ tx: x, ty: y, got: false });
      }
      else if (char === 'E') {
        gameState.enemies.push({ x: x * T, y: y * T, w: 12, h: 12, dir: -1, dead: 0, alive: true });
      }
      else if (char === '^' || char === 'S') {
        gameState.hazards.push({ x: x * T + 1, y: y * T + 6, w: T - 2, h: T - 6, dir: 'up', tx: x, ty: y });
      }
      else if (char === 'v') {
        gameState.hazards.push({ x: x * T + 1, y: y * T, w: T - 2, h: T - 6, dir: 'down', tx: x, ty: y });
      }
      else if (char === '<') {
        gameState.hazards.push({ x: x * T + 6, y: y * T + 1, w: T - 6, h: T - 2, dir: 'left', tx: x, ty: y });
      }
      else if (char === '>') {
        gameState.hazards.push({ x: x * T, y: y * T + 1, w: T - 6, h: T - 2, dir: 'right', tx: x, ty: y });
      }
      else if (char === 'W') {
        gameState.saws.push({
          x: x * T + T / 2,
          y: y * T + T / 2,
          r: 12,
          rotSpeed: 0.22,
          angle: 0,
          moving: false
        });
      }
      else if (char === 'M') {
        gameState.saws.push({
          x: x * T + T / 2,
          y: y * T + T / 2,
          startX: x * T + T / 2,
          startY: y * T + T / 2,
          r: 12,
          rotSpeed: 0.28,
          angle: 0,
          moving: true,
          vx: 1.2,
          vy: 0,
          progress: 0,
          step: 1.2,
          maxDist: 64
        });
      }
      else if (char === 'P') {
        gameState.spawnX = x * T;
        gameState.spawnY = y * T;
      }
      else if (char === 'G') {
        gameState.girlX = x * T;
        gameState.girlY = y * T;
      }
    }
  }
}

export function solid(tx, ty) {
  if (tx < 0 || tx >= COLS) return true;
  if (ty < 0 || ty >= ROWS) return false;
  if (map[ty][tx] === '#') return true;
  if (map[ty][tx] === 'B') {
    const c = gameState.crumbles.find(b => b.tx === tx && b.ty === ty);
    return c ? !c.collapsed : true;
  }
  return false;
}
